"""Executive Dashboard: nine KPIs, trends, mix and rule-based insights."""
import streamlit as st

from analytics import executive as ex
from components import charts, data, theme
from components.filters import current
from components.formatting import money, number, pct, score
from components.insights import render_insights
from components.kpi_cards import kpi_row
from components.layout import page_header, section

f = current()
page_header("Executive Dashboard", "Headline performance of the marketplace for the selected filters.")

k = data.q(ex.calculate_executive_kpis, f)
kpi_row([
    ("total_revenue", money(k["total_revenue"], True)),
    ("total_orders", number(k["total_orders"])),
    ("total_customers", number(k["total_customers"])),
    ("avg_order_value", money(k["avg_order_value"])),
    ("avg_customer_revenue", money(k["avg_customer_revenue"])),
    ("avg_review_score", score(k["avg_review_score"])),
    ("repeat_purchase_rate", pct(k["repeat_purchase_rate"])),
    ("on_time_delivery_rate", pct(k["on_time_delivery_rate"])),
    ("late_delivery_rate", pct(k["late_delivery_rate"])),
], per_row=3)
st.caption("Revenue is product revenue (item prices); freight is excluded and it is not profit — the dataset has no cost data.")

monthly = data.q(ex.get_monthly_revenue, f)
orders = data.q(ex.get_monthly_orders, f)
c1, c2 = st.columns(2)
with c1:
    charts.chart_card("Monthly revenue", charts.line_fig(monthly, "year_month", {"Revenue": "revenue"}, "Revenue", money=True)
                      if not monthly.empty else None, monthly, "exec_monthly_revenue",
                      "Months with very few orders (dataset edges) are partial and not comparable.")
with c2:
    charts.chart_card("Monthly orders", charts.line_fig(orders, "year_month", {"Orders": "orders"}, "Orders")
                      if not orders.empty else None, orders, "exec_monthly_orders")

cats = data.q(ex.get_top_categories, f, top_n=10)
states = data.q(ex.get_revenue_by_state, f)
c3, c4 = st.columns(2)
with c3:
    charts.chart_card("Top 10 categories by revenue", charts.bar_fig(cats, "category", "revenue", money=True)
                      if not cats.empty else None, cats, "exec_top_categories")
with c4:
    top_states = states.head(10)
    charts.chart_card("Top 10 states by revenue", charts.bar_fig(top_states, "state", "revenue", money=True)
                      if not top_states.empty else None, states, "exec_top_states")

pay = data.q(ex.get_payment_distribution, f)
status = data.q(ex.get_order_status_distribution, f)
rev = data.q(ex.get_review_trend, f)
c5, c6 = st.columns(2)
with c5:
    fig = None
    if not pay.empty:
        pay_col = pay.columns[0]
        val = "revenue" if "revenue" in pay.columns else pay.columns[1]
        fig = charts.bar_fig(pay, pay_col, val, money=(val == "revenue"),
                             color_map={p: theme.entity_color("payment", p) for p in pay[pay_col]})
    charts.chart_card("Payment methods", fig, pay, "exec_payment", "Orders are grouped by their primary payment type.")
with c6:
    fig = None
    if not status.empty:
        s_col = status.columns[0]
        v_col = "orders" if "orders" in status.columns else status.columns[1]
        fig = charts.bar_fig(status, s_col, v_col)
    charts.chart_card("Order status", fig, status, "exec_status")
fig = charts.line_fig(rev, rev.columns[0], {"Average review score": "avg_review_score"}, "Score (1–5)") if (not rev.empty and "avg_review_score" in rev.columns) else None
charts.chart_card("Average review score by month", fig, rev, "exec_reviews")

section("Insights", "Generated by transparent rules; open “Why am I seeing this?” to see each rule and its evidence.")
render_insights(data.q(ex.generate_executive_insights, f))
